-- The TPC-H schema as HammerDB (TPROC-H, src/mysql/mysqlolap.tcl) creates it
-- for MySQL: database latin1 / latin1_swedish_ci, character columns with the
-- BINARY attribute (latin1_bin), the same primary keys and secondary indexes,
-- and the same foreign keys (allowed since 2026-11-17). Difference:
-- SECONDARY_ENGINE = duckdb (HammerDB adds the engine only for HeatWave).
DROP DATABASE IF EXISTS tpch;
CREATE DATABASE tpch CHARACTER SET latin1 COLLATE latin1_swedish_ci;
USE tpch;

CREATE TABLE REGION (R_REGIONKEY INT NOT NULL, R_NAME CHAR(25) BINARY NULL,
  R_COMMENT VARCHAR(152) BINARY NULL, PRIMARY KEY (R_REGIONKEY)) SECONDARY_ENGINE = duckdb;
CREATE TABLE NATION (N_NATIONKEY INT NOT NULL, N_NAME CHAR(25) BINARY NULL,
  N_REGIONKEY INT NULL, N_COMMENT VARCHAR(152) BINARY NULL, PRIMARY KEY (N_NATIONKEY),
  INDEX NATION_REGIONKEY_FKIDX (N_REGIONKEY)) SECONDARY_ENGINE = duckdb;
CREATE TABLE SUPPLIER (S_SUPPKEY INT NOT NULL, S_NATIONKEY INT NULL,
  S_COMMENT VARCHAR(102) BINARY NULL, S_NAME CHAR(25) BINARY NULL,
  S_ADDRESS VARCHAR(40) BINARY NULL, S_PHONE CHAR(15) BINARY NULL,
  S_ACCTBAL DECIMAL(10,2) NULL, PRIMARY KEY (S_SUPPKEY)) SECONDARY_ENGINE = duckdb;
CREATE TABLE CUSTOMER (C_CUSTKEY INT NOT NULL, C_MKTSEGMENT CHAR(10) BINARY NULL,
  C_NATIONKEY INT NULL, C_NAME VARCHAR(25) BINARY NULL, C_ADDRESS VARCHAR(40) BINARY NULL,
  C_PHONE CHAR(15) BINARY NULL, C_ACCTBAL DECIMAL(10,2) NULL,
  C_COMMENT VARCHAR(118) BINARY NULL, PRIMARY KEY (C_CUSTKEY),
  INDEX CUSTOMER_NATION_FKIDX (C_NATIONKEY)) SECONDARY_ENGINE = duckdb;
CREATE TABLE PART (P_PARTKEY INT NOT NULL, P_TYPE VARCHAR(25) BINARY NULL, P_SIZE INT NULL,
  P_BRAND CHAR(10) BINARY NULL, P_NAME VARCHAR(55) BINARY NULL,
  P_CONTAINER CHAR(10) BINARY NULL, P_MFGR CHAR(25) BINARY NULL,
  P_RETAILPRICE DECIMAL(10,2) NULL, P_COMMENT VARCHAR(23) BINARY NULL,
  PRIMARY KEY (P_PARTKEY)) SECONDARY_ENGINE = duckdb;
CREATE TABLE PARTSUPP (PS_PARTKEY INT NOT NULL, PS_SUPPKEY INT NOT NULL,
  PS_SUPPLYCOST INT NOT NULL, PS_AVAILQTY INT NULL, PS_COMMENT VARCHAR(199) BINARY NULL,
  PRIMARY KEY (PS_PARTKEY, PS_SUPPKEY), INDEX PARTSUPP_PART_FKIDX (PS_PARTKEY),
  INDEX PARTSUPP_SUPPLIER_FKIDX (PS_SUPPKEY)) SECONDARY_ENGINE = duckdb;
CREATE TABLE ORDERS (O_ORDERDATE DATE NULL, O_ORDERKEY BIGINT NOT NULL, O_CUSTKEY INT NOT NULL,
  O_ORDERPRIORITY CHAR(15) BINARY NULL, O_SHIPPRIORITY INT NULL, O_CLERK CHAR(15) BINARY NULL,
  O_ORDERSTATUS CHAR(1) BINARY NULL, O_TOTALPRICE DECIMAL(10,2) NULL,
  O_COMMENT VARCHAR(79) BINARY NULL, PRIMARY KEY (O_ORDERKEY)) SECONDARY_ENGINE = duckdb;
CREATE TABLE LINEITEM (L_SHIPDATE DATE NULL, L_ORDERKEY BIGINT NOT NULL,
  L_DISCOUNT DECIMAL(10,2) NOT NULL, L_EXTENDEDPRICE DECIMAL(10,2) NOT NULL,
  L_SUPPKEY INT NOT NULL, L_QUANTITY INT NOT NULL, L_RETURNFLAG CHAR(1) BINARY NULL,
  L_PARTKEY INT NOT NULL, L_LINESTATUS CHAR(1) BINARY NULL, L_TAX DECIMAL(10,2) NOT NULL,
  L_COMMITDATE DATE NULL, L_RECEIPTDATE DATE NULL, L_SHIPMODE CHAR(10) BINARY NULL,
  L_LINENUMBER INT NOT NULL, L_SHIPINSTRUCT CHAR(25) BINARY NULL,
  L_COMMENT VARCHAR(44) BINARY NULL, PRIMARY KEY (L_ORDERKEY, L_LINENUMBER),
  INDEX LINEITEM_PART_SUPP_FKIDX (L_PARTKEY, L_SUPPKEY),
  INDEX IDX_LINEITEM_ORDERKEY_FKIDX (L_ORDERKEY)) SECONDARY_ENGINE = duckdb;

ALTER TABLE NATION ADD CONSTRAINT NATION_FK1 FOREIGN KEY (N_REGIONKEY) REFERENCES REGION (R_REGIONKEY);
ALTER TABLE SUPPLIER ADD CONSTRAINT SUPPLIER_FK1 FOREIGN KEY (S_NATIONKEY) REFERENCES NATION (N_NATIONKEY);
ALTER TABLE CUSTOMER ADD CONSTRAINT CUSTOMER_FK1 FOREIGN KEY (C_NATIONKEY) REFERENCES NATION (N_NATIONKEY);
ALTER TABLE PARTSUPP ADD CONSTRAINT PARTSUPP_FK1 FOREIGN KEY (PS_PARTKEY) REFERENCES PART (P_PARTKEY);
ALTER TABLE PARTSUPP ADD CONSTRAINT PARTSUPP_FK2 FOREIGN KEY (PS_SUPPKEY) REFERENCES SUPPLIER (S_SUPPKEY);
ALTER TABLE ORDERS ADD CONSTRAINT ORDERS_FK1 FOREIGN KEY (O_CUSTKEY) REFERENCES CUSTOMER (C_CUSTKEY);
ALTER TABLE LINEITEM ADD CONSTRAINT LINEITEM_FK1 FOREIGN KEY (L_ORDERKEY) REFERENCES ORDERS (O_ORDERKEY);
ALTER TABLE LINEITEM ADD CONSTRAINT LINEITEM_FK2 FOREIGN KEY (L_PARTKEY, L_SUPPKEY) REFERENCES PARTSUPP (PS_PARTKEY, PS_SUPPKEY);
